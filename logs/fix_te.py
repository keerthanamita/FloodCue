def esc(value):
    # build entities without writing them literally (avoid entity mangling in transit)
    amp, lt, gt = chr(38), chr(60), chr(62)
    return (value.replace(amp, amp + 'amp;')
                 .replace(lt, lt + 'lt;')
                 .replace(gt, gt + 'gt;'))


def main():
    te_dir = Path('app/src/main/res/values-te')
    applied = {}
    for f in sorted(te_dir.glob('strings*.xml')):
        text = f.read_text(encoding='utf-8')
        orig = text
        for key, val in FIX.items():
            pat = re.compile(r'(<string name="' + re.escape(key) + r'">)(.*?)(</string>)', re.S)
            text, n = pat.subn(lambda m, v=esc(val): m.group(1) + v + m.group(3), text, count=1)
            if n:
                applied[key] = f.name
        if text != orig:
            f.write_text(text, encoding='utf-8')

    missing = [k for k in FIX if k not in applied]
    print('applied:', len(applied), 'of', len(FIX))
    if missing:
        print('NOT FOUND:', missing)
    return 0 if not missing else 1


